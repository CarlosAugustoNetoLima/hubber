/* Texto visível no idioma pedido. Sem tradução cadastrada, fica o original. */
export function traduzir(texto, idioma) {
  if (idioma !== 'en' || typeof texto !== 'string') return texto;
  return Object.prototype.hasOwnProperty.call(EN, texto) ? EN[texto] : texto;
}
